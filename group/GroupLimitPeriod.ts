/**
 * Периодичность лимита участника группы. По образцу `DateFrequency` из dfa
 * (значения совместимы с moment: 'month', 'week' и т.д.).
 *
 * Лимит `GroupMember.limit` — потолок расхода участника в пределах ОДНОГО окна
 * выбранной периодичности. «Исчерпал» означает: сумма расхода из группы за
 * текущее окно достигла лимита. С началом нового окна отсчёт начинается заново,
 * то есть лимит автоматически восстанавливается — отдельного «сброса» не нужно.
 *
 * `TOTAL` — особый случай: лимит за всё время, без периодов и без сброса (самый
 * простой режим). Чтобы «дать ещё» после исчерпания, администратор поднимает
 * сам лимит.
 */
export enum GroupLimitPeriod {
    TOTAL = 'total',
    YEAR = 'year',
    QUARTER = 'quarter',
    MONTH = 'month',
    WEEK = 'week',
    DAY = 'day',
}
